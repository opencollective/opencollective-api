import { randomUUID } from 'crypto';

import bcrypt from 'bcrypt';
import { z } from 'zod';

import OrderStatuses from '../constants/order-status';
import roles from '../constants/roles';
import { TransactionKind } from '../constants/transaction-kind';
import { TransactionTypes } from '../constants/transactions';
import { sessionCache } from '../lib/cache';
import { crypto } from '../lib/encryption';
import { TwoFactorMethod } from '../lib/two-factor-authentication/two-factor-methods';
import { Application, Member, Order, Transaction, UserTwoFactorMethod } from '../models';

import {
  accountHandle,
  actorHandle,
  createActor,
  createHost,
  createHostedCollective,
  createPayoutMethod,
  createSubmittedExpense,
  defineRecipe,
  type Recipe,
} from './builders';

/** The base32 TOTP secret the product stores (`addTwoFactorAuthTokenToIndividual` accepts the same shape). */
const totpSecret = z.string().regex(/^[A-Z2-7]{103,104}$/);

const individualInputs = z
  .object({
    /** A password the user can sign in with (6 to 72 bytes, as `setPassword` accepts). */
    password: z
      .string()
      .refine(password => Buffer.byteLength(password) >= 6 && Buffer.byteLength(password) <= 72)
      .optional(),
    /** Two-factor authentication with an authenticator app, from this secret (the journey computes the codes). */
    twoFactorSecret: totpSecret.optional(),
    /** A second, unrelated user (`other`), e.g. whose email address is already taken. */
    otherUser: z.boolean().default(false),
    /** An OAuth application owned by the user, as `createApplication` leaves it. */
    oauthApplication: z
      .object({ name: z.string().trim().min(1).max(100), redirectUri: z.string().url() })
      .strict()
      .optional(),
    /** Sign-in link tokens for the user: one valid, one expired. */
    loginTokens: z.boolean().default(false),
  })
  .strict();

const profileInputs = z
  .object({
    /** When the user became an admin of `adminOf` (ISO date). */
    adminSince: z.string().date(),
    /** One-time contributions (EUR cents) the user already made to `backed`, oldest first. */
    contributions: z.array(z.number().int().positive()).min(1).max(10),
    /** Descriptions of the pending expenses the user already submitted to `backed`. */
    expenses: z.array(z.string().trim().min(1).max(255)).min(1).max(10),
  })
  .strict();

const userUrls = (slug: string) => ({
  profile: `/${slug}`,
  info: `/dashboard/${slug}/info`,
  advanced: `/dashboard/${slug}/advanced`,
  userSecurity: `/dashboard/${slug}/user-security`,
  forDevelopers: `/dashboard/${slug}/for-developers`,
  authorizedApps: `/dashboard/${slug}/authorized-apps`,
});

export const userRecipes: Record<string, Recipe> = {
  /**
   * One signed-up user (`user`) with no membership, and optionally the sign-in credentials the journey needs:
   * a password, two-factor authentication, sign-in link tokens, an OAuth application of their own, or a second
   * user (`other`). Signing in, changing credentials and managing tokens are the journeys' behaviour.
   */
  individual: defineRecipe({
    inputs: individualInputs,
    build: async (ctx, inputs) => {
      const { transaction } = ctx;
      const user = await createActor(ctx, 'user');
      const other = inputs.otherUser ? await createActor(ctx, 'other') : null;

      if (inputs.password) {
        // What `setPassword` stores, without its activity
        const passwordHash = await bcrypt.hash(inputs.password, 10);
        await user.update({ passwordHash, passwordUpdatedAt: new Date() }, { transaction });
      }

      if (inputs.twoFactorSecret) {
        // A restored database hands out user ids again, while the API's Redis keeps the 2FA sessions and failed-code
        // counters of the previous database's users. Forget those of this id, so the journey is asked for its code
        // and has its whole budget. Only this new user's keys: if the request rolls back, the id is never reused.
        const staleSessions = await sessionCache.keys(`2fa:${user.id}:*`);
        if (staleSessions.length) {
          await sessionCache.delete(staleSessions);
        }
        await sessionCache.delete([`user_2FA_graphql_${user.id}`, `user_2FA_endpoint_${user.id}`]);
        ctx.checkConnection();
        await UserTwoFactorMethod.create(
          {
            UserId: user.id,
            method: TwoFactorMethod.TOTP,
            name: 'Authenticator',
            data: { secret: crypto.encrypt(inputs.twoFactorSecret) },
          },
          { transaction },
        );
      }

      let application = null;
      if (inputs.oauthApplication) {
        ctx.checkConnection();
        // Credentials are generated by the model, as for `createApplication`
        const app = await Application.create(
          {
            type: 'oAuth',
            name: inputs.oauthApplication.name,
            description: 'An independent Playwright OAuth application',
            callbackUrl: inputs.oauthApplication.redirectUri,
            CreatedByUserId: user.id,
            CollectiveId: user.CollectiveId,
          },
          { transaction },
        );
        application = { name: app.name, clientId: app.clientId, clientSecret: app.clientSecret };
      }

      return {
        actors: { user: actorHandle(user), ...(other && { other: actorHandle(other) }) },
        accounts: {},
        expenses: {},
        vendors: {},
        urls: userUrls(user.collective.slug),
        ...(application && { application }),
        ...(inputs.loginTokens && {
          // The token of the emailed sign-in link (`generateLoginLink`), and one that expired
          loginTokens: {
            valid: user.jwt({ scope: 'login', lastLoginAt: null }),
            expired: user.jwt({ scope: 'login', lastLoginAt: null }, -100000),
          },
        }),
      };
    },
  }),

  /**
   * The public profile of a user (`user`) with history: an admin of the Collective `adminOf` since `adminSince`,
   * a financial contributor of `backed` (both hosted by `host`, in EUR) through one-time contributions,
   * and the submitter of pending expenses to `backed`. Reading the profile is the journey's behaviour.
   */
  'user-profile': defineRecipe({
    inputs: profileInputs,
    build: async (ctx, inputs) => {
      const { transaction } = ctx;
      const user = await createActor(ctx, 'user');
      const hostAdmin = await createActor(ctx, 'host-admin');
      const host = await createHost(ctx, hostAdmin, { currency: 'EUR' });
      const backed = await createHostedCollective(ctx, 'backed', { host, creator: hostAdmin, admins: [hostAdmin] });

      // Approved and hosted: the profile only lists roles in approved Accounts
      const adminOf = await createHostedCollective(ctx, 'admin-of', { host, creator: user });
      const adminSince = new Date(inputs.adminSince);
      await Member.create(
        {
          role: roles.ADMIN,
          MemberCollectiveId: user.CollectiveId,
          CollectiveId: adminOf.id,
          CreatedByUserId: user.id,
          since: adminSince,
          createdAt: adminSince,
        },
        { transaction },
      );

      // Paid one-time contributions, one ledger pair each. Hooks are skipped: no activity or email.
      for (const [index, amount] of inputs.contributions.entries()) {
        ctx.checkConnection();
        const chargedAt = new Date(Date.now() - (inputs.contributions.length - index) * 60_000);
        const order = await Order.create(
          {
            CreatedByUserId: user.id,
            FromCollectiveId: user.CollectiveId,
            CollectiveId: backed.id,
            totalAmount: amount,
            platformTipAmount: 0,
            currency: 'EUR',
            quantity: 1,
            status: OrderStatuses.PAID,
            description: `Financial contribution to ${backed.name}`,
            processedAt: chargedAt,
          },
          { transaction },
        );
        const ledgerBase = {
          kind: TransactionKind.CONTRIBUTION,
          currency: 'EUR' as const,
          hostCurrency: 'EUR' as const,
          hostCurrencyFxRate: 1,
          hostFeeInHostCurrency: 0,
          platformFeeInHostCurrency: 0,
          paymentProcessorFeeInHostCurrency: 0,
          HostCollectiveId: host.id,
          OrderId: order.id,
          CreatedByUserId: user.id,
          TransactionGroup: randomUUID(),
          description: order.description,
          createdAt: chargedAt,
          clearedAt: chargedAt,
        };
        await Transaction.create(
          {
            ...ledgerBase,
            type: TransactionTypes.CREDIT,
            amount,
            amountInHostCurrency: amount,
            netAmountInCollectiveCurrency: amount,
            CollectiveId: backed.id,
            FromCollectiveId: user.CollectiveId,
          },
          { transaction, hooks: false },
        );
        await Transaction.create(
          {
            ...ledgerBase,
            type: TransactionTypes.DEBIT,
            amount: -amount,
            amountInHostCurrency: -amount,
            netAmountInCollectiveCurrency: -amount,
            CollectiveId: user.CollectiveId,
            FromCollectiveId: backed.id,
          },
          { transaction, hooks: false },
        );
      }
      await Member.create(
        {
          role: roles.BACKER,
          MemberCollectiveId: user.CollectiveId,
          CollectiveId: backed.id,
          CreatedByUserId: user.id,
          since: new Date(),
        },
        { transaction },
      );

      const payoutMethod = await createPayoutMethod(ctx, {
        account: user.collective,
        creator: user,
        name: `Saved payout ${ctx.tag}`,
        currency: 'EUR',
      });
      for (const description of inputs.expenses) {
        await createSubmittedExpense(ctx, {
          account: backed,
          submitter: user,
          payoutMethod,
          description,
          items: [{ description, amount: 1000 }],
        });
      }

      return {
        actors: { user: actorHandle(user), hostAdmin: actorHandle(hostAdmin) },
        accounts: { host: accountHandle(host), backed: accountHandle(backed), adminOf: accountHandle(adminOf) },
        expenses: {},
        vendors: {},
        urls: { profile: `/${user.collective.slug}` },
      };
    },
  }),
};
