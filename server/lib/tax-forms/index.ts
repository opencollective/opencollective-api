import config from 'config';
import { get } from 'lodash';

import {
  TAX_FORM_IGNORED_EXPENSE_STATUSES,
  TAX_FORM_IGNORED_EXPENSE_TYPES,
  US_TAX_FORM_THRESHOLD_FOR_PAYPAL,
  US_TAX_FORM_THRESHOLD_POST_2026,
  US_TAX_FORM_THRESHOLD_PRE_2026,
} from '../../constants/tax-form';
import { Collective, Expense } from '../../models';
import LegalDocument, { LEGAL_DOCUMENT_TYPE } from '../../models/LegalDocument';
import { uploadToS3 } from '../awsS3';

export const getTaxFormsS3Bucket = (): string => {
  return get(config, 'taxForms.aws.s3.bucket');
};

export const amountsRequireTaxForm = (
  paypalTotal: number,
  otherTotal: number,
  year: number,
  options?: {
    isUSEntity?: boolean;
    taxFormThresholds?: { US?: number; NON_US?: number };
    includePayPalExpenses?: boolean;
  },
): boolean => {
  const isUSEntity = options?.isUSEntity;
  const customThreshold = isUSEntity === false ? options?.taxFormThresholds?.NON_US : options?.taxFormThresholds?.US;
  // PayPal collects tax forms based on its own thresholds and is responsible for tax reporting
  // for those payees, so we exclude PayPal expenses by default. Hosts must explicitly opt-in
  // by setting `includePayPalExpenses: true` on the host's TAX_FORM_THRESHOLDS policy.
  const effectivePaypalTotal = options?.includePayPalExpenses === true ? paypalTotal : 0;

  if (customThreshold !== undefined && customThreshold !== null) {
    const total = (effectivePaypalTotal || 0) + (otherTotal || 0);
    return total >= customThreshold;
  }

  if (effectivePaypalTotal >= US_TAX_FORM_THRESHOLD_FOR_PAYPAL) {
    return true;
  } else if (year >= 2026) {
    return otherTotal >= US_TAX_FORM_THRESHOLD_POST_2026;
  } else {
    return otherTotal >= US_TAX_FORM_THRESHOLD_PRE_2026;
  }
};

export const expenseMightBeSubjectToTaxForm = (expense: Expense): boolean => {
  return (
    !(TAX_FORM_IGNORED_EXPENSE_TYPES as readonly string[]).includes(expense.type) &&
    !(TAX_FORM_IGNORED_EXPENSE_STATUSES as readonly string[]).includes(expense.status)
  );
};

export function encryptAndUploadTaxFormToS3(
  buffer: Buffer,
  collective: Collective,
  year: number | string,
  valuesHash: string = 'none',
) {
  const bucket = getTaxFormsS3Bucket();
  const key = createTaxFormFilename({ collective, year, documentType: LEGAL_DOCUMENT_TYPE.US_TAX_FORM, valuesHash });
  const encryptedBuffer = LegalDocument.encrypt(buffer);
  return uploadToS3({
    Body: encryptedBuffer,
    Bucket: bucket,
    Key: key,
    Metadata: { collectiveId: `${collective.id}`, valuesHash },
  });
}

/**
 * Whether `key` (an S3 key in the tax forms bucket) is a tax form file that belongs to `collectiveId`.
 * Keys are generated by `createTaxFormFilename` as `US_TAX_FORM/<year>/<name>-<collectiveId>[_<valuesHash>].pdf`.
 * `<name>` can contain any character (including `-` and `/`), but `valuesHash` is hexadecimal, so anchoring
 * on `-<collectiveId>[_<hex>].pdf` at the end of the key is unambiguous.
 *
 * Legacy keys (`US_TAX_FORM_<year>_<name>.pdf`, pre-2023) are not bound to an account ID and are only
 * accepted when `allowLegacy` is set.
 */
export const isTaxFormS3KeyForAccount = (
  key: string,
  collectiveId: number,
  { allowLegacy = false }: { allowLegacy?: boolean } = {},
): boolean => {
  if (!key || typeof key !== 'string' || !Number.isInteger(collectiveId) || collectiveId <= 0) {
    return false;
  }

  const documentType = LEGAL_DOCUMENT_TYPE.US_TAX_FORM;
  const currentFormat = new RegExp(`^${documentType}/\\d{4}/.+-${collectiveId}(?:_[a-f0-9]+)?\\.pdf$`);
  if (currentFormat.test(key)) {
    return true;
  }

  return allowLegacy && new RegExp(`^${documentType}_(?:201\\d|202[0-2])_[^/]+\\.pdf$`).test(key);
};

function createTaxFormFilename({ collective, year, documentType, valuesHash }) {
  if (year >= 2023) {
    return valuesHash && valuesHash !== 'none'
      ? `${documentType}/${year}/${collective.name || collective.legalName}-${collective.id}_${valuesHash}.pdf`
      : `${documentType}/${year}/${collective.name || collective.legalName}-${collective.id}.pdf`;
  } else {
    return `${documentType}_${year}_${collective.name}.pdf`;
  }
}
