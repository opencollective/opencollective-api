import { expect } from 'chai';
import { Plaid, PlaidError } from 'plaid';
import sinon from 'sinon';

import * as PlaidClient from '../../../../server/lib/plaid/client';
import {
  connectPlaidAccount,
  disconnectPlaidAccount,
  generatePlaidLinkToken,
  refreshPlaidSubAccounts,
} from '../../../../server/lib/plaid/connect';
import { makePlaidClientStub, PlaidClientStub, plaidLinkTokenCreateResponse } from '../../../mocks/plaid';
import {
  fakeActiveHost,
  fakeConnectedAccount,
  fakeTransactionsImport,
  fakeUser,
} from '../../../test-helpers/fake-data';

/* eslint-disable camelcase */
const plaidErrorBody = (error_code: string): Plaid.PlaidError => ({
  error_type: 'INVALID_INPUT',
  error_code,
  error_message: error_code,
  display_message: null,
  request_id: 'request-id',
});
/* eslint-enable camelcase */

describe('server/lib/plaid/connect', () => {
  describe('with a stubbed Plaid client', () => {
    let sandbox: sinon.SinonSandbox;
    let stubPlaidAPI: PlaidClientStub;

    before(() => {
      sandbox = sinon.createSandbox();
    });

    beforeEach(() => {
      stubPlaidAPI = makePlaidClientStub(sandbox);
      sandbox.stub(PlaidClient, 'getPlaidClient').returns(stubPlaidAPI);
    });

    afterEach(() => {
      sandbox.restore();
    });

    describe('connectPlaidAccount', () => {
      /** An admin and their host, with a link token generated by that admin */
      const setupLink = async () => {
        const admin = await fakeUser();
        const host = await fakeActiveHost({ admin });
        stubPlaidAPI.link.createToken.resolves(plaidLinkTokenCreateResponse);
        await generatePlaidLinkToken(admin, host, { products: ['transactions'], countries: ['US'], locale: 'en' });
        return { admin, host, linkToken: plaidLinkTokenCreateResponse.link_token };
      };

      it('reads INVALID_PUBLIC_TOKEN from the typed error', async () => {
        const { admin, host, linkToken } = await setupLink();
        stubPlaidAPI.item.exchangePublicToken.rejects(
          new Plaid.BadRequestError(plaidErrorBody('INVALID_PUBLIC_TOKEN')),
        );
        await expect(connectPlaidAccount(admin, host, 'public-sandbox-1', linkToken, {})).to.be.rejectedWith(
          'Provided Plaid public token is invalid',
        );
      });

      it('reports other Plaid errors', async () => {
        const { admin, host, linkToken } = await setupLink();
        stubPlaidAPI.item.exchangePublicToken.rejects(
          new Plaid.InternalServerError(plaidErrorBody('INTERNAL_SERVER_ERROR')),
        );
        await expect(connectPlaidAccount(admin, host, 'public-sandbox-1', linkToken, {})).to.be.rejectedWith(
          'An error occurred while connecting Plaid',
        );
      });

      it('treats a failure without a Plaid response as a network error', async () => {
        const { admin, host, linkToken } = await setupLink();
        stubPlaidAPI.item.exchangePublicToken.rejects(new TypeError('fetch failed'));
        await expect(connectPlaidAccount(admin, host, 'public-sandbox-1', linkToken, {})).to.be.rejectedWith(
          'A network occurred while connecting Plaid',
        );
      });
    });

    describe('disconnectPlaidAccount', () => {
      it('removes the item and detaches the transactions import', async () => {
        const connectedAccount = await fakeConnectedAccount({ service: 'plaid' });
        const transactionsImport = await fakeTransactionsImport({
          type: 'PLAID',
          CollectiveId: connectedAccount.CollectiveId,
          ConnectedAccountId: connectedAccount.id,
        });
        stubPlaidAPI.item.remove.resolves({ request_id: 'request-id' }); // eslint-disable-line camelcase

        await disconnectPlaidAccount(connectedAccount);

        expect(stubPlaidAPI.item.remove).to.have.been.calledOnceWith({ access_token: connectedAccount.token }); // eslint-disable-line camelcase
        await transactionsImport.reload();
        expect(transactionsImport.ConnectedAccountId).to.be.null;
      });

      it('reads the Plaid error code from the typed error', async () => {
        const connectedAccount = await fakeConnectedAccount({ service: 'plaid' });
        stubPlaidAPI.item.remove.rejects(new Plaid.BadRequestError(plaidErrorBody('INVALID_ACCESS_TOKEN')));
        await expect(disconnectPlaidAccount(connectedAccount)).to.be.rejectedWith(
          'Provided Plaid access token is invalid',
        );
      });

      it('reports other Plaid errors', async () => {
        const connectedAccount = await fakeConnectedAccount({ service: 'plaid' });
        stubPlaidAPI.item.remove.rejects(new Plaid.InternalServerError(plaidErrorBody('INTERNAL_SERVER_ERROR')));
        await expect(disconnectPlaidAccount(connectedAccount)).to.be.rejectedWith(
          'An error occurred while disconnecting the Plaid account',
        );
      });

      it('treats a failure without a Plaid response as a network error', async () => {
        const connectedAccount = await fakeConnectedAccount({ service: 'plaid' });
        stubPlaidAPI.item.remove.rejects(
          new PlaidError({ message: 'Timeout exceeded when calling POST /item/remove.' }),
        );
        await expect(disconnectPlaidAccount(connectedAccount)).to.be.rejectedWith(
          'A network error occurred while disconnecting the Plaid account',
        );
      });
    });
  });

  describe('refreshPlaidSubAccounts', () => {
    const sandbox = sinon.createSandbox();

    afterEach(() => {
      sandbox.restore();
    });

    const baseAccount: Partial<Plaid.AccountBase> = {
      account_id: 'acc-1', // eslint-disable-line camelcase
      name: 'Checking',
      official_name: 'Official Checking', // eslint-disable-line camelcase
      mask: '0000',
      subtype: Plaid.AccountSubtype.Checking,
      type: Plaid.AccountType.Depository,
    };

    const refresh = async (accounts: Partial<Plaid.AccountBase>[], importData = undefined) => {
      const stubPlaidAPI = makePlaidClientStub(sandbox);
      stubPlaidAPI.accounts.get = sandbox.stub().resolves({ accounts });
      sandbox.stub(PlaidClient, 'getPlaidClient').returns(stubPlaidAPI);
      const connectedAccount = await fakeConnectedAccount({ service: 'plaid' });
      const transactionsImport = await fakeTransactionsImport({
        type: 'PLAID',
        ConnectedAccountId: connectedAccount.id,
        data: importData,
      });
      await refreshPlaidSubAccounts(connectedAccount, transactionsImport);
      await transactionsImport.reload();
      return transactionsImport;
    };

    it('stores the available accounts', async () => {
      const transactionsImport = await refresh([baseAccount]);
      expect(transactionsImport.data.plaid.availableAccounts).to.deep.eq([
        {
          accountId: 'acc-1',
          mask: '0000',
          name: 'Checking',
          officialName: 'Official Checking',
          subtype: 'checking',
          type: 'depository',
        },
      ]);
    });

    it('keeps the rest of the import data (sync cursor, attempts, lock)', async () => {
      const lockedAt = new Date().toISOString();
      const transactionsImport = await refresh([baseAccount], {
        lockedAt,
        plaid: { lastSyncCursor: 'cursor-1', syncAttempt: 2, lastSyncErrorMessage: 'boom' },
      });

      expect(transactionsImport.data.lockedAt).to.eq(lockedAt);
      expect(transactionsImport.data.plaid.lastSyncCursor).to.eq('cursor-1');
      expect(transactionsImport.data.plaid.syncAttempt).to.eq(2);
      expect(transactionsImport.data.plaid.lastSyncErrorMessage).to.eq('boom');
      expect(transactionsImport.data.plaid.availableAccounts).to.have.length(1);
    });

    it('stores accounts with a null official_name, mask or subtype', async () => {
      const transactionsImport = await refresh([
        { ...baseAccount, account_id: 'acc-1', official_name: null }, // eslint-disable-line camelcase
        { ...baseAccount, account_id: 'acc-2', mask: null, subtype: null }, // eslint-disable-line camelcase
      ]);

      const accounts = transactionsImport.data.plaid.availableAccounts;
      expect(accounts).to.have.length(2);
      expect(accounts[0]).to.include({ accountId: 'acc-1', officialName: 'Checking' });
      expect(accounts[1]).to.include({ accountId: 'acc-2', mask: '', subtype: 'other' });
    });
  });
});
